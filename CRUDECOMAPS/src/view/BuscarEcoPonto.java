    private void BuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BuscarActionPerformed
        EcoPonto equi = new EcoPonto();
        EcoMapsDAO equiDAO = new EcoMapsDAO();
        

        String  patrimonio;
        
        patrimonio = patrimonioBox.getText();
        equi.setPatrimonio(patrimonio);

        try {
            equiDAO.pesquisar(equi);
        } catch (java.sql.SQLException ex) {
            System.getLogger(BuscarEcoPonto.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        equipamentoBox.setText(equi.getNome());
        descricaoBox.setText(equi.getDescricao());
    }//GEN-LAST:event_BuscarActionPerformed

