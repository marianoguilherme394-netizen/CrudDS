    private void EditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditarActionPerformed
        EcoPonto equipamento = new EcoPonto();
        int n1 = Integer.parseInt(JOptionPane.showInputDialog("Tem certeza que deseja editar? 1. SIM 2 NÃO"));

        if(n1 == 1){
            String patrimonio;
            patrimonio = dadosBox.getText();
            equipamento.setPatrimonio(patrimonio);

            EditarEcoPonto altEq = new EditarEcoPonto();
            altEq.setVisible(true);
        } else {
            JOptionPane.showMessageDialog(null, "Exclusão cancelada");
        }
    }//GEN-LAST:event_EditarActionPerformed

