    private void BuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BuscarActionPerformed
        
        EcoPonto equipamento = new EcoPonto();
        EcoMapsDAO equipamentoDao = new EcoMapsDAO();
        
        String patrimonio;
        patrimonio = patrimonioBox.getText();
        equipamento.setPatrimonio(patrimonio);
        
        try {
            equipamentoDao.pesquisar(equipamento);
            if(equipamento.getNome() != null) {
                dadosBox.setText("Nome: " + equipamento.getNome() + "\n" 
                               + "Descricao " + equipamento.getDescricao() + "\n" 
                               + "Patrimonio: " + equipamento.getPatrimonio() + "\n");
            } else { 
                 dadosBox.setText("Equipamento não encontrado");
            }
        } catch (SQLException ex) {
            System.out.println("Não encontrado" + "\n" + ex);
        }
    }//GEN-LAST:event_BuscarActionPerformed

